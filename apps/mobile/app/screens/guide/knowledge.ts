/**
 * "많이 찾는 질문"에 고정으로 올릴 글입니다.
 * 조사한 검색 수요(초보 시작·미세먼지·러닝화·무릎·체중·대회·자세·습관)에서 골라 손으로 정했습니다.
 * 자동 순위가 아니라 고정 목록이라 매번 같은 순서로 보입니다.
 */
export const popularKnowledgeIds = [
  'beginner-how-much',
  'beginner-everyday',
  'weather-fine-dust',
  'gear-first-shoe',
  'injury-knee',
  'weight-not-losing',
  'race-first-10k',
  'form-landing',
] as const;

export function popularKnowledgeCards(cards: KnowledgeCard[] = knowledgeCards): KnowledgeCard[] {
  return popularKnowledgeIds
    .map((id) => cards.find((card) => card.id === id))
    .filter((card): card is KnowledgeCard => Boolean(card));
}

/** 분류별 글 수입니다. 화면의 칩 옆 숫자에 씁니다. */
export function knowledgeCountsByCategory(
  cards: KnowledgeCard[] = knowledgeCards,
): Record<KnowledgeCategory, number> {
  const counts = Object.fromEntries(
    knowledgeCategories.map((category) => [category, 0]),
  ) as Record<KnowledgeCategory, number>;
  counts['전체'] = cards.length;
  for (const card of cards) counts[card.category] += 1;
  return counts;
}

export function filterKnowledgeByCategory(
  category: KnowledgeCategory,
  cards: KnowledgeCard[] = knowledgeCards,
): KnowledgeCard[] {
  if (category === '전체') return cards;
  return cards.filter((card) => card.category === category);
}

function searchableText(card: KnowledgeCard): string {
  return `${card.question} ${card.answer.join(' ')} ${card.keywords.join(' ')} ${card.category}`.toLocaleLowerCase(
    'ko-KR',
  );
}

/** 검색창에 적은 말을 낱말 단위로 자릅니다. 화면의 강조 표시도 이 낱말을 씁니다. */
export function knowledgeSearchTerms(query: string): string[] {
  return query
    .normalize('NFKC')
    .toLocaleLowerCase('ko-KR')
    .split(/\s+/)
    .map((term) => term.trim())
    .filter(Boolean);
}

/** 질문·답변·검색 낱말·분류를 한 번에 훑는 단순 부분 문자열 검색입니다. */
export function searchKnowledge(
  query: string,
  cards: KnowledgeCard[] = knowledgeCards,
): KnowledgeCard[] {
  const terms = knowledgeSearchTerms(query);
  if (terms.length === 0) return cards;
  return cards.filter((card) => {
    const haystack = searchableText(card);
    return terms.every((term) => haystack.includes(term));
  });
}

/**
 * 검색 결과가 0건일 때 "이런 걸 찾으셨나요?"로 보여 줄 비슷한 질문입니다.
 * 낱말을 두 글자씩 잘라 한 조각이라도 겹치면 점수를 주고, 질문에서 겹치면 점수를 더 줍니다.
 */
export function suggestKnowledge(
  query: string,
  cards: KnowledgeCard[] = knowledgeCards,
  limit = 5,
): KnowledgeCard[] {
  const terms = knowledgeSearchTerms(query);
  if (terms.length === 0) return popularKnowledgeCards(cards).slice(0, limit);

  const pieces = new Set<string>();
  for (const term of terms) {
    if (term.length <= 2) {
      pieces.add(term);
      continue;
    }
    for (let index = 0; index + 2 <= term.length; index += 1) {
      pieces.add(term.slice(index, index + 2));
    }
  }

  const scored = cards
    .map((card) => {
      const haystack = searchableText(card);
      const question = card.question.toLocaleLowerCase('ko-KR');
      let score = 0;
      for (const piece of pieces) {
        if (haystack.includes(piece)) score += 1;
        if (question.includes(piece)) score += 2;
      }
      return { card, score };
    })
    .filter((entry) => entry.score > 0)
    .sort((left, right) => right.score - left.score);

  const picked = scored.slice(0, limit).map((entry) => entry.card);
  return picked.length > 0 ? picked : popularKnowledgeCards(cards).slice(0, limit);
}

/**
 * 검색어가 들어간 자리를 앞뒤로 잘라 한 줄 미리보기를 만듭니다.
 * 질문만 보고는 왜 이 글이 걸렸는지 알 수 없어서, 답변에서 걸린 대목을 보여 줍니다.
 */
export function knowledgeSnippet(card: KnowledgeCard, query: string, width = 46): string | undefined {
  const terms = knowledgeSearchTerms(query);
  if (terms.length === 0) return undefined;
  const question = card.question.toLocaleLowerCase('ko-KR');
  const term = terms.find((value) => !question.includes(value) && card.answer.some((line) => line.toLocaleLowerCase('ko-KR').includes(value)));
  if (!term) return undefined;
  const line = card.answer.find((value) => value.toLocaleLowerCase('ko-KR').includes(term));
  if (!line) return undefined;
  const at = line.toLocaleLowerCase('ko-KR').indexOf(term);
  const from = Math.max(0, at - Math.floor(width / 3));
  const to = Math.min(line.length, from + width);
  return `${from > 0 ? '…' : ''}${line.slice(from, to).trim()}${to < line.length ? '…' : ''}`;
}

/** 강조 표시를 위해 글자를 "검색어에 걸린 조각"과 "아닌 조각"으로 나눕니다. */
export function splitBySearchTerms(
  text: string,
  query: string,
): { text: string; matched: boolean }[] {
  const terms = knowledgeSearchTerms(query).filter((term) => term.length > 0);
  if (terms.length === 0) return [{ text, matched: false }];

  const lower = text.toLocaleLowerCase('ko-KR');
  const hits: { start: number; end: number }[] = [];
  for (const term of terms) {
    let at = lower.indexOf(term);
    while (at !== -1) {
      hits.push({ start: at, end: at + term.length });
      at = lower.indexOf(term, at + term.length);
    }
  }
  if (hits.length === 0) return [{ text, matched: false }];

  hits.sort((left, right) => left.start - right.start);
  const merged: { start: number; end: number }[] = [];
  for (const hit of hits) {
    const last = merged[merged.length - 1];
    if (last && hit.start <= last.end) {
      last.end = Math.max(last.end, hit.end);
      continue;
    }
    merged.push({ ...hit });
  }

  const parts: { text: string; matched: boolean }[] = [];
  let cursor = 0;
  for (const hit of merged) {
    if (hit.start > cursor) parts.push({ text: text.slice(cursor, hit.start), matched: false });
    parts.push({ text: text.slice(hit.start, hit.end), matched: true });
    cursor = hit.end;
  }
  if (cursor < text.length) parts.push({ text: text.slice(cursor), matched: false });
  return parts;
}

export function findKnowledgeCards(
  category: KnowledgeCategory,
  query: string,
  cards: KnowledgeCard[] = knowledgeCards,
): KnowledgeCard[] {
  return searchKnowledge(query, filterKnowledgeByCategory(category, cards));
}
