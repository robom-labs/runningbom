/** 남은 시간과 경과 시간을 사람이 말하듯 안내합니다. */
export function progressLine(
  elapsedSeconds: number,
  totalSeconds: number,
): string {
  const elapsedMinutes = Math.round(elapsedSeconds / 60);
  const remainingMinutes = Math.max(0, Math.round((totalSeconds - elapsedSeconds) / 60));
  const ratio = elapsedSeconds / totalSeconds;

  if (Math.abs(ratio - 0.5) < 0.04) {
    return `${elapsedMinutes}분 지났어요. 딱 절반 왔어요, 남은 ${remainingMinutes}분도 지금 리듬으로 가요.`;
  }
  if (Math.abs(ratio - 0.25) < 0.04) {
    return `${elapsedMinutes}분 지났어요. 4분의 1을 지났고 ${remainingMinutes}분 남았어요.`;
  }
  if (Math.abs(ratio - 0.75) < 0.04) {
    return `${elapsedMinutes}분 지났어요. 4분의 3까지 왔고 ${remainingMinutes}분 남았어요.`;
  }
  if (remainingMinutes <= 3) {
    return `${remainingMinutes}분 남았어요. 마지막까지 자세만 지켜 주세요.`;
  }
  if (remainingMinutes <= 10) {
    return `${elapsedMinutes}분 지났어요. ${remainingMinutes}분 남았고 이제 끝이 보여요.`;
  }
  return `${elapsedMinutes}분 지났어요. ${remainingMinutes}분 남았어요.`;
}
