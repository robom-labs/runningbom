/** 한 덩어리를 말하는 데 걸리는 시간(초)입니다. */
export function blockSpokenSeconds(block: LongformBlock): number {
  // 한국어 TTS 기준으로 초당 5.5자 정도이고, 문장 사이에 잠깐씩 쉽니다.
  return block.lines.reduce((total, line) => total + Math.max(2, line.length / 5.5) + 0.4, 0);
}

/** 그 주제의 설명 덩어리입니다. */
export function teachingFor(theme: BodyTheme): LongformBlock | undefined {
  return teachingBlocks.find((block) => block.theme === theme);
}
