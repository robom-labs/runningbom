// 보조 프로젝트입니다. 달리기 자체가 아니라 "달리기를 더 잘 하게 해 주는 것"들입니다.
//
// 훈련·계획과 다른 점:
//   훈련은 시간을 재고 몸을 씁니다. 보조 프로젝트는 며칠에 걸쳐 하나씩 챙기는 일입니다.
//   자세 다듬기, 호흡 찾기, 신발 고르기, 아침 습관 만들기 같은 것들입니다.
//
// 도전과 다른 점:
//   도전은 활동 기록을 해석해서 저절로 채워집니다.
//   보조 프로젝트는 기록으로 알 수 없어서, 사용자가 직접 "했어요"를 눌러 표시합니다.
//
// 이 층이 절대 하지 않는 일:
//   **훈련량을 늘리라고 시키지 않습니다.** 여기 있는 것은 전부 달리기 밖의 일이거나,
//   달리는 동안 신경 쓰는 방법입니다. "더 뛰세요"는 여기 들어가지 않습니다.
//   아픈 곳을 진단하지도 않습니다. 아프면 병원에 가라고 말합니다.

export type ProjectCategory = 'FORM' | 'BREATH' | 'GEAR' | 'HABIT' | 'BODY' | 'MIND' | 'SAFETY';

export const projectCategoryLabels: Record<ProjectCategory, string> = {
  FORM: '자세',
  BREATH: '호흡',
  GEAR: '장비',
  HABIT: '습관',
  BODY: '몸 돌보기',
  MIND: '마음',
  SAFETY: '안전',
};

export type ProjectStep = {
  /** 저장에 쓰는 고유 ID입니다. 한 번 정하면 바꾸지 않습니다. */
  id: string;
  title: string;
  detail: string;
};

export type SupportProject = {
  id: string;
  title: string;
  subtitle: string;
  description: string;
  category: ProjectCategory;
  steps: ProjectStep[];
};

/** 단계를 짧게 적기 위한 도우미입니다. ID는 프로젝트 ID에서 자동으로 만듭니다. */
function project(
  id: string,
  category: ProjectCategory,
  title: string,
  subtitle: string,
  description: string,
  steps: [string, string][],
): SupportProject {
  return {
    id,
    title,
    subtitle,
    description,
    category,
    steps: steps.map(([stepTitle, detail], index) => ({
      id: `${id}-s${index + 1}`,
      title: stepTitle,
      detail,
    })),
  };
}

