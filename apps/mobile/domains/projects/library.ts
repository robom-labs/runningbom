/** 목록이 규칙을 지키는지 봅니다. 빈 배열이면 통과입니다. */
export function validateProjects(): string[] {
  const problems: string[] = [];
  const seenProjects = new Set<string>();
  const seenSteps = new Set<string>();

  for (const item of supportProjects) {
    if (seenProjects.has(item.id)) problems.push(`프로젝트 ID가 겹칩니다: ${item.id}`);
    seenProjects.add(item.id);

    if (!item.title) problems.push(`${item.id}: 제목이 없습니다.`);
    if (!item.description) problems.push(`${item.id}: 설명이 없습니다.`);
    if (item.steps.length === 0) problems.push(`${item.id}: 단계가 없습니다.`);

    for (const step of item.steps) {
      if (seenSteps.has(step.id)) problems.push(`단계 ID가 겹칩니다: ${step.id}`);
      seenSteps.add(step.id);
      if (!step.title) problems.push(`${step.id}: 제목이 없습니다.`);
      if (!step.detail) problems.push(`${step.id}: 설명이 없습니다.`);
    }
  }
  return problems;
}

export type ProjectProgress = {
  project: SupportProject;
  doneStepIds: string[];
  /** 0~1입니다. */
  ratio: number;
  finished: boolean;
  /** 다음에 할 단계입니다. 다 했으면 없습니다. */
  nextStep?: ProjectStep;
  label: string;
};

/** 프로젝트 하나의 진행 상황입니다. 같은 값을 넣으면 언제나 같은 결과가 나옵니다. */
export function projectProgress(
  item: SupportProject,
  doneIds: readonly string[],
): ProjectProgress {
  const owned = new Set(item.steps.map((step) => step.id));
  const done = doneIds.filter((id) => owned.has(id));
  const nextStep = item.steps.find((step) => !done.includes(step.id));
  return {
    project: item,
    doneStepIds: done,
    ratio: item.steps.length === 0 ? 0 : done.length / item.steps.length,
    finished: done.length >= item.steps.length,
    ...(nextStep ? { nextStep } : {}),
    label: `${done.length} / ${item.steps.length}단계`,
  };
}

/**
 * 지금 보여 줄 프로젝트를 고릅니다.
 * 20개를 늘어놓으면 고르다 지칩니다. 하던 것 먼저, 그다음 안 해 본 것입니다.
 */
export function activeProjects(
  doneIds: readonly string[],
  limit = 3,
): ProjectProgress[] {
  const all = supportProjects.map((item) => projectProgress(item, doneIds));
  const started = all.filter((item) => !item.finished && item.doneStepIds.length > 0);
  const fresh = all.filter((item) => item.doneStepIds.length === 0);
  const done = all.filter((item) => item.finished);
  // 하던 것을 먼저 끝내게 합니다. 벌여 놓기만 하면 아무것도 안 끝납니다.
  return [...started, ...fresh, ...done].slice(0, limit);
}
